-- 신상 소식 승인: 회차의 승인·발송 예정 컬럼, 승인 기록, 제외 기록
-- 발송 상태(SENDING, SENT 등)는 상태 컬럼 값으로만 늘어나서 컬럼은 더 필요 없다

ALTER TABLE news_batch
    ADD COLUMN approved_at TIMESTAMP(6),
    ADD COLUMN send_at TIMESTAMP(6),                -- 푸시 발송 예정 시각. 목록 공개 시각도 같다. 푸시 대상이 없으면 NULL
    ADD COLUMN changed_after_vote_by VARCHAR(30);   -- 첫 표 이후 [제외]·[되돌리기]를 누른 사람(슬랙 회원 ID). 다음 승인자에게 변경이 있었다고 알린다

-- 승인 표. 같은 사람이 두 번 눌러도 1표다
CREATE TABLE news_approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES news_batch (id),
    slack_user_id VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_news_approval_batch_user UNIQUE (batch_id, slack_user_id)
);

-- 사람이 [제외]를 누른 링크. 다음 수집에서 같은 링크가 다시 올라오지 않게 한다. [다시 수집]으로 버린 묶음은 기록하지 않는다
CREATE TABLE news_exclusion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic VARCHAR(30) NOT NULL,
    link_key TEXT NOT NULL,
    slack_user_id VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_news_exclusion_topic_link UNIQUE (topic, link_key)
);
