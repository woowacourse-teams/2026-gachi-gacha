-- 신상 소식 공개: 모든 회원이 함께 읽는 공개 소식, 회원별 구독과 마지막으로 탭을 본 시각

-- 공개 소식. 내용은 수집 후보(news_candidate)를 참조하고, 같은 소식인지는 link_key 로 판단한다
CREATE TABLE news_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic VARCHAR(30) NOT NULL,
    candidate_id BIGINT NOT NULL UNIQUE REFERENCES news_candidate (id),
    link_key TEXT NOT NULL,
    published_at TIMESTAMP(6) NOT NULL,             -- 목록에 공개하는 시각. 승인할 때 정하고, 이 시각이 지나야 목록에 보인다
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_news_item_topic_link UNIQUE (topic, link_key)
);
CREATE INDEX idx_news_item_topic_published ON news_item (topic, published_at DESC);

-- 회원별 주제 설정. 구독을 꺼도 행은 남겨서 끈 기록(unsubscribed_at)이 남는다
CREATE TABLE news_member_topic (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    topic VARCHAR(30) NOT NULL,
    subscribed BOOLEAN NOT NULL,
    subscribed_at TIMESTAMP(6),
    unsubscribed_at TIMESTAMP(6),                   -- 가장 최근에 끈 시각
    last_viewed_at TIMESTAMP(6),                    -- 탭을 마지막으로 본 시각. 새 소식 표시에 쓴다
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_news_member_topic UNIQUE (member_id, topic)
);
