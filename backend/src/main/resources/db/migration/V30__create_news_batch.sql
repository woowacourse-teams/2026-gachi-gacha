-- 신상 소식: 수집 회차와 수집 후보. 승인·발송 컬럼은 그 기능을 만드는 단계에서 추가한다
-- periods 의 날짜는 UTC 기준이다(xAI 기간 제한이 UTC 날짜 단위). 시각 컬럼은 다른 테이블과 같이 서버 기본 시간대다.

CREATE TABLE news_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic VARCHAR(30) NOT NULL,
    run_name VARCHAR(20) NOT NULL,                  -- MONDAY, THURSDAY, RECOLLECT
    status VARCHAR(20) NOT NULL,
    dry_run BOOLEAN NOT NULL,
    prompt_version VARCHAR(30) NOT NULL,
    periods JSONB NOT NULL,                         -- 계정별 수집 기간과 그 계정의 수집 성공 여부
    usage JSONB NOT NULL,                           -- 호출 수, 검색량, 토큰, 비용
    warnings TEXT,                                  -- 실행 보고에 남길 경고. 한 줄에 하나
    slack_channel_id VARCHAR(30),
    slack_message_ts VARCHAR(30),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

-- 주제마다 수집 중이거나 승인 대기 중인 회차는 하나뿐이다. 같은 기간을 동시에 수집하지 않게 막는다
CREATE UNIQUE INDEX uk_news_batch_active ON news_batch (topic)
    WHERE status IN ('COLLECTING', 'AWAITING_APPROVAL');

CREATE TABLE news_candidate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES news_batch (id),
    section VARCHAR(20) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    title TEXT NOT NULL,
    start_date DATE,
    end_date DATE,
    link TEXT,
    posted_at TIMESTAMP(6),                         -- X 게시물 번호로 계산한 원본 게시 시각
    review VARCHAR(20) NOT NULL,                    -- PUSH_TARGET, TAB_ONLY, NEEDS_CHECK, ENDED
    carried_from_id BIGINT REFERENCES news_candidate (id),
    detail JSONB NOT NULL,                          -- 보여주기만 하는 값 (날짜 표기, 장소, 상품, 예약 방법 등)
    created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_news_candidate_batch ON news_candidate (batch_id);
