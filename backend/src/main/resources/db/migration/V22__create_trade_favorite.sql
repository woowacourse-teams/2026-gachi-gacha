CREATE TABLE trade_favorite (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                member_id BIGINT NOT NULL,
                                trade_id BIGINT NOT NULL,
                                created_at TIMESTAMP(6) NOT NULL,
                                updated_at TIMESTAMP(6) NOT NULL,

                                CONSTRAINT uk_trade_favorite_member_trade
                                    UNIQUE (member_id, trade_id),

                                CONSTRAINT fk_trade_favorite_member
                                    FOREIGN KEY (member_id) REFERENCES member (id),

                                CONSTRAINT fk_trade_favorite_trade
                                    FOREIGN KEY (trade_id) REFERENCES trade (id) ON DELETE CASCADE
);

CREATE INDEX idx_trade_favorite_trade
    ON trade_favorite (trade_id);
