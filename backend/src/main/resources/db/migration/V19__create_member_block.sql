CREATE TABLE member_block
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT       NOT NULL,
    blocked_id BIGINT       NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),

    CONSTRAINT fk_member_block_blocker
        FOREIGN KEY (blocker_id) REFERENCES member (id),
    CONSTRAINT fk_member_block_blocked
        FOREIGN KEY (blocked_id) REFERENCES member (id),
    CONSTRAINT uk_member_block_pair
        UNIQUE (blocker_id, blocked_id),
    CONSTRAINT chk_member_block_nㅡot_self
        CHECK (blocker_id <> blocked_id)
);
