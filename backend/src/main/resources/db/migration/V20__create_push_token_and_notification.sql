CREATE TABLE push_token
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT       NOT NULL,
    token      VARCHAR(512) NOT NULL,
    platform   VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),

    CONSTRAINT fk_push_token_member
        FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT uk_push_token_token
        UNIQUE (token),
    CONSTRAINT chk_push_token_platform
        CHECK (platform IN ('ANDROID', 'IOS'))
);

CREATE INDEX idx_push_token_member_id ON push_token (member_id);

-- 게시글·댓글이 삭제돼도 알림 기록은 남기므로 대상에는 FK를 걸지 않는다.
CREATE TABLE notification
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_id BIGINT       NOT NULL,
    type        VARCHAR(30)  NOT NULL,
    trade_id    BIGINT       NOT NULL,
    comment_id  BIGINT       NOT NULL,
    actor_name  VARCHAR(255) NOT NULL,
    preview     VARCHAR(100) NOT NULL,
    is_read     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6),

    CONSTRAINT fk_notification_receiver
        FOREIGN KEY (receiver_id) REFERENCES member (id),
    CONSTRAINT uk_notification_comment_receiver
        UNIQUE (comment_id, receiver_id)
);

CREATE INDEX idx_notification_receiver_id ON notification (receiver_id, id DESC);
CREATE INDEX idx_notification_unread ON notification (receiver_id) WHERE is_read = FALSE;
