CREATE TABLE favorite_signal (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 member_id BIGINT NOT NULL,
                                 favorite_type VARCHAR(20) NOT NULL,
                                 target_id BIGINT NOT NULL,
                                 signal_type VARCHAR(20) NOT NULL,
                                 signal_value VARCHAR(100) NOT NULL,
                                 weight DOUBLE PRECISION NOT NULL,
                                 created_at TIMESTAMP(6) NOT NULL,
                                 updated_at TIMESTAMP(6) NOT NULL,

                                 CONSTRAINT uk_favorite_signal
                                     UNIQUE (member_id, favorite_type, target_id, signal_type, signal_value),

                                 CONSTRAINT fk_favorite_signal_member
                                     FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);

CREATE INDEX idx_favorite_signal_match
    ON favorite_signal (signal_type, signal_value, member_id);

CREATE INDEX idx_favorite_signal_target
    ON favorite_signal (favorite_type, target_id);
