CREATE TABLE gacha_favorite (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                member_id BIGINT NOT NULL,
                                gacha_id BIGINT NOT NULL,
                                created_at TIMESTAMP(6) NOT NULL,
                                updated_at TIMESTAMP(6) NOT NULL,
                                CONSTRAINT uk_gacha_favorite_member_gacha UNIQUE (member_id, gacha_id),
                                CONSTRAINT fk_gacha_favorite_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE,
                                CONSTRAINT fk_gacha_favorite_gacha FOREIGN KEY (gacha_id) REFERENCES gacha (id) ON DELETE CASCADE
);

CREATE INDEX idx_gacha_favorite_gacha ON gacha_favorite (gacha_id);

CREATE TABLE store_favorite (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                member_id BIGINT NOT NULL,
                                store_id BIGINT NOT NULL,
                                created_at TIMESTAMP(6) NOT NULL,
                                updated_at TIMESTAMP(6) NOT NULL,
                                CONSTRAINT uk_store_favorite_member_store UNIQUE (member_id, store_id),
                                CONSTRAINT fk_store_favorite_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE,
                                CONSTRAINT fk_store_favorite_store FOREIGN KEY (store_id) REFERENCES store (id) ON DELETE CASCADE
);

CREATE INDEX idx_store_favorite_store ON store_favorite (store_id);
